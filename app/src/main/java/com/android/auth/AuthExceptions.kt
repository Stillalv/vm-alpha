package com.android.auth

open class AppAuthException(val errorCode: String, message: String) : Exception(message)
class AppAuthInvalidUserException(code: String, msg: String) : AppAuthException(code, msg)
class AppAuthInvalidCredentialsException(code: String, msg: String) : AppAuthException(code, msg)
class AppAuthUserCollisionException(code: String, msg: String, val email: String? = null) : AppAuthException(code, msg)
class AppAuthWeakPasswordException(code: String, msg: String, val reason: String? = null) : AppAuthException(code, msg)
class AppAuthRecentLoginRequiredException(code: String, msg: String) : AppAuthException(code, msg)
class AppAuthActionCodeException(code: String, msg: String) : AppAuthException(code, msg)
class AppAuthEmailException(code: String, msg: String) : AppAuthException(code, msg)
class AppAuthMultiFactorException(code: String, msg: String) : AppAuthException(code, msg)
class AppAuthWebException(code: String, msg: String) : AppAuthException(code, msg)
class AppAuthMissingActivityForCaptchaException(code: String, msg: String) : AppAuthException(code, msg)
class AppNetworkException(msg: String) : AppAuthException("ERROR_NETWORK_REQUEST_FAILED", msg)
class AppTooManyRequestsException(msg: String) : AppAuthException("ERROR_TOO_MANY_REQUESTS", msg)
class AppApiNotAvailableException(msg: String) : AppAuthException("ERROR_API_NOT_AVAILABLE", msg)
class AppNoSignedInUserException(msg: String) : AppAuthException("ERROR_NO_SIGNED_IN_USER", msg)
